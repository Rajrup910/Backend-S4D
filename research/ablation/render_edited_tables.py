# Table: conformal coverage (marginal vs Mondrian class-conditional vs bipartite)
# ---------------------------------------------------------------------------------------

def build_conformal_table() -> str:
    rows = {(r["method"], r["calibrator"], r["alpha"]): r
            for r in _csv("results/session9/conformal_test.csv")}

    lines = [
        GENERATED_BY.rstrip("\n"),
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Conformal coverage on the HAM10000 held-out test split ($N=1502$), marginal "
        r"vs. Mondrian class-conditional vs. bipartite calibration, at $\alpha=0.05$ and "
        r"$\alpha=0.10$. Serious coverage is coverage restricted to the escalating classes; "
        r"FRR is the false-referral rate (a serious lesion's conformal set omitting every "
        r"escalating class). Source: \texttt{results/session9/conformal\_test.csv}, the single "
        r"pre-registered test pass. Coverage here is audited empirically, not guaranteed: the "
        r"OOF calibration scores come from five fold models and the test scores from the full-"
        r"train ensemble, so no exact finite-sample guarantee transfers.}",
        r"\label{tab:conformal_edited}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{6pt}",
        r"\begin{tabular}{llccc}",
        r"\toprule",
        r"Method & Calibrator & Marginal cov. & Serious cov. & FRR [95\% CI] \\",
        r"\midrule",
    ]
    for alpha in CONFORMAL_ALPHAS:
        lines.append(r"\multicolumn{5}{l}{\textit{$\alpha = %s$}} \\" % _f(alpha, 2))
        for method in CONFORMAL_METHODS:
            for calibrator, calib_label in CONFORMAL_CALIBRATORS:
                r = rows[(method, calibrator, alpha)]
                lines.append(
                    f"{method} & {calib_label} & {_f(r['marginal_coverage'], 4)} & "
                    f"{_f(r['escalating_coverage'], 4)} & "
                    f"{_f(r['frr'], 4)} [{_f(r['frr_ci_lo'], 4)}, {_f(r['frr_ci_hi'], 4)}] \\\\"
                )
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines += [
        r"\end{tabular}",
        r"\end{table*}",
        "",
    ]
    return "\n".join(lines)


