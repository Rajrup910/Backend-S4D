# Table: age-band escalation sensitivity, merged with the age-rule recovery columns
# ---------------------------------------------------------------------------------------

def build_age_table() -> str:
    intervals = _csv("research/stats/results_oof/age_gap_intervals.csv")
    by_split_band = {(r["split"], r["band"]): r for r in intervals}
    oof_rule = {r["group"]: r for r in _csv("research/agerule/results_oof/lambda_by_band.csv")}
    test_rule = {(r["band"], r["rule"]): r for r in _csv("results/session9/agerule_test.csv")}

    def cp_or_boot(r) -> str:
        return "CP" if r["interval_method"] == "clopper_pearson" else "boot"

    lines = [
        GENERATED_BY.rstrip("\n"),
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Escalation sensitivity by patient age band under argmax, merged with the "
        r"age-conditional $\lambda$-rule's recovery. Validation and OOF columns are argmax "
        r"only (the rule is fitted on OOF and reported from there); the test columns compare "
        r"argmax against the frozen rule from the single pre-registered Session~9 test pass. "
        r"Intervals marked CP are exact Clopper--Pearson; those marked boot are lesion-grouped "
        r"percentile bootstrap. Sources: "
        r"\texttt{research/stats/results\_oof/age\_gap\_intervals.csv} (val, OOF argmax), "
        r"\texttt{research/agerule/results\_oof/lambda\_by\_band.csv} (OOF rule, cross-fitted, "
        r"point estimate only), \texttt{results/session9/agerule\_test.csv} (test argmax and "
        r"rule).}",
        r"\label{tab:agegap_edited}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{5pt}",
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r" & \multicolumn{3}{c}{Internal / Out-of-fold} & \multicolumn{2}{c}{Held-out test} \\",
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-6}",
        r"Age band & Val argmax & OOF argmax & OOF rule ($\lambda$) & Test argmax & Test rule ($\lambda$) \\",
        r"\midrule",
    ]
    for band in AGE_BANDS:
        v = by_split_band[("val", band)]
        o = by_split_band[("oof", band)]
        orule = oof_rule[band]
        t_arg = test_rule[(band, "argmax")]
        t_rule = test_rule[(band, "lambda_rule")]
        val_cell = (f"${_f(v['sensitivity'], 3)}$ [{_f(v['ci_lo'], 3)}, {_f(v['ci_hi'], 3)}]"
                    f"$^{{\\text{{{cp_or_boot(v)}}}}}$")
        oof_cell = (f"${_f(o['sensitivity'], 3)}$ [{_f(o['ci_lo'], 3)}, {_f(o['ci_hi'], 3)}]"
                    f"$^{{\\text{{{cp_or_boot(o)}}}}}$")
        oof_rule_cell = f"${_f(orule['fit_sensitivity'], 3)}$ ($\\lambda={_f(orule['lam'], 2)}$)"
        t_arg_cell = (f"${_f(t_arg['escalation_sensitivity'], 3)}$ "
                      f"[{_f(t_arg['sens_ci_lo'], 3)}, {_f(t_arg['sens_ci_hi'], 3)}]")
        t_rule_cell = (f"${_f(t_rule['escalation_sensitivity'], 3)}$ "
                       f"[{_f(t_rule['sens_ci_lo'], 3)}, {_f(t_rule['sens_ci_hi'], 3)}]")
        label = band.replace("<", "$<$").replace("-", "--")
        lines.append(f"{label} & {val_cell} & {oof_cell} & {oof_rule_cell} & "
                     f"{t_arg_cell} & {t_rule_cell} \\\\")

    all_v = by_split_band[("val", "ALL")]
    all_o = by_split_band.get(("oof", "ALL"))
    t_arg_all = test_rule[("ALL", "argmax")]
    t_rule_all = test_rule[("ALL", "lambda_rule")]
    val_all_cell = (f"${_f(all_v['sensitivity'], 3)}$ [{_f(all_v['ci_lo'], 3)}, {_f(all_v['ci_hi'], 3)}]"
                    f"$^{{\\text{{{cp_or_boot(all_v)}}}}}$")
    if all_o is not None:
        oof_all_cell = (f"${_f(all_o['sensitivity'], 3)}$ [{_f(all_o['ci_lo'], 3)}, {_f(all_o['ci_hi'], 3)}]"
                        f"$^{{\\text{{{cp_or_boot(all_o)}}}}}$")
    else:
        oof_all_cell = "---"
    t_arg_all_cell = (f"${_f(t_arg_all['escalation_sensitivity'], 3)}$ "
                      f"[{_f(t_arg_all['sens_ci_lo'], 3)}, {_f(t_arg_all['sens_ci_hi'], 3)}]")
    t_rule_all_cell = (f"${_f(t_rule_all['escalation_sensitivity'], 3)}$ "
                       f"[{_f(t_rule_all['sens_ci_lo'], 3)}, {_f(t_rule_all['sens_ci_hi'], 3)}]")
    lines.append(r"\midrule")
    lines.append(f"All ages & {val_all_cell} & {oof_all_cell} & --- & "
                 f"{t_arg_all_cell} & {t_rule_all_cell} \\\\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="render in memory and report drift without writing the files")
    args = parser.parse_args(argv)

    outputs = {
        LADDER_TABLE: build_ladder_table(),
        CONFORMAL_TABLE: build_conformal_table(),
        AGE_TABLE: build_age_table(),
    }

    for path, tex in outputs.items():
        target = resolve(path)
        if args.check:
            current = target.read_text(encoding="utf-8") if target.is_file() else ""
            status = "up to date" if current == tex else "DRIFTED"
            print(f"{status}: {path}")
            if current != tex:
                return 1
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(tex, encoding="utf-8")
        rows = sum(1 for line in tex.splitlines() if line.strip().endswith(r"\\"))
        print(f"Wrote {target.relative_to(REPO_ROOT)} ({rows} rows, {len(tex):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
